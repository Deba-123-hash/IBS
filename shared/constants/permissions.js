/**
 * Checks whether a given role has the requested permission
 * @param {string} userRole
 * @param {string} requiredPermission
 * @returns {boolean}
 */
export const hasPermission = (userRole, requiredPermission) => {
  if (!userRole) return false;
  if (userRole === 'SUPER_ADMIN') {
    // Explicit forbidden rules for all roles including SUPER_ADMIN
    const immutableForbidden = [
      'AUDIT_DELETE',
      'PAYMENT_DELETE',
      'GATE_LOG_DELETE',
      'TRANSACTION_DELETE',
      'RECONCILIATION_DELETE'
    ];
    if (immutableForbidden.includes(requiredPermission)) return false;
    return true;
  }
  const rolePerms = ROLE_PERMISSIONS[userRole] || [];
  // Direct match or mapped permission
  const target = PERMISSIONS[requiredPermission] || requiredPermission;
  return rolePerms.includes(target) || rolePerms.includes(requiredPermission);
};

