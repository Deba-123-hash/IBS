export const hasPermission = (userRole, requiredPermission) => {
  if (!userRole) return false;
  if (userRole === 'SUPER_ADMIN') return true;
  const rolePerms = ROLE_PERMISSIONS[userRole] || [];
  return rolePerms.includes(requiredPermission);
};
